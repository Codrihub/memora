// Vite bundle step. Pages and the service worker are rendered by
// scripts/build-pages.mjs, which runs after this.

import { fileURLToPath } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import { defineConfig } from 'vite';

const webDir = fileURLToPath(new URL('.', import.meta.url));
// MEMORA_ASSETS_OUT lets a test build land outside the live asset directory.
const assetsDir =
  process.env.MEMORA_ASSETS_OUT || fileURLToPath(new URL('../crates/http/assets', import.meta.url));

export default defineConfig({
  plugins: [tailwindcss()],
  root: webDir,
  publicDir: false,
  build: {
    outDir: assetsDir,
    // The server whitelists exact asset names; never clear the directory.
    emptyOutDir: false,
    target: 'es2020',
    sourcemap: false,
    cssCodeSplit: false,
    minify: 'esbuild',
    rollupOptions: {
      input: fileURLToPath(new URL('src/main.ts', import.meta.url)),
      output: {
        // Single IIFE chunk: the pages load it with a plain script tag.
        format: 'iife',
        entryFileNames: 'app.js',
        chunkFileNames: 'app.js',
        assetFileNames: '[name][extname]',
        banner: '/* Generated by Vite. Do not edit. Source: web/src. */',
        inlineDynamicImports: true,
      },
    },
  },
});
